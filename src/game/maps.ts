import { TERRAINS } from './terrain';
import type { Color, GameMap, MapSection, Piece, PropKind, Terrain, Theme } from './types';

/** 지형을 따로 지정하지 않은 조각은 3차선 포장도로입니다. */
const p = (length: number, curve = 0, hill = 0): Piece => ({
  length,
  curve,
  hill,
  terrain: TERRAINS.road3,
});

const on =
  (terrain: Terrain) =>
  (...pieces: Piece[]): Piece[] =>
    pieces.map((piece) => ({ ...piece, terrain }));

const r2 = on(TERRAINS.road2);
const r4 = on(TERRAINS.road4);
const dirt = on(TERRAINS.dirt);
const bridge = on(TERRAINS.bridge);
const ford = on(TERRAINS.ford);
const ice = on(TERRAINS.ice);
const space = on(TERRAINS.space);

const LAVA: Color = [230, 90, 20];

const WHITE: Color = [240, 240, 240];

/** 색은 하늘 위, 하늘 아래, 땅, 도로, 연석, 안개, 차선 순서입니다. */
function theme(
  name: string,
  skyTop: Color,
  skyBottom: Color,
  ground: Color,
  road: Color,
  rumble: Color,
  fog: Color,
  lane: Color = WHITE,
): Theme {
  return { name, skyTop, skyBottom, ground, road, rumble, lane, fog };
}

const section = (t: Theme, props: PropKind[], pieces: Piece[]): MapSection => ({
  theme: t,
  props,
  pieces,
});

